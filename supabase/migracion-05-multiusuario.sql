-- =====================================================================
--  Migración 05: varios usuarios, cada uno con sus propios datos
--  (productos, clientes, pedidos y ajustes separados por usuario)
--  Pegar en Supabase > SQL Editor > New query > Run  (una sola vez)
--  (Requiere haber ejecutado antes las migraciones 01 a 04.)
--
--  IMPORTANTE: todo lo que existe hoy (productos, clientes, pedidos) se
--  asigna a UN usuario: el que indiques abajo en v_email. Si lo dejas en
--  null, se usa el primer usuario creado en Authentication > Users.
-- =====================================================================

-- ---------- 1) Columna "dueño" en cada tabla ----------
alter table public.settings  add column if not exists owner_id uuid references auth.users(id) on delete cascade;
alter table public.settings  add column if not exists slug text;                                  -- nombre corto del enlace del catálogo: catalogo.html?t=SLUG
alter table public.settings  add column if not exists is_default boolean not null default false;  -- tienda que abren los enlaces antiguos (sin ?t=)
alter table public.products  add column if not exists owner_id uuid references auth.users(id) on delete cascade;
alter table public.customers add column if not exists owner_id uuid references auth.users(id) on delete cascade;
alter table public.orders    add column if not exists owner_id uuid references auth.users(id) on delete cascade;

-- ---------- 2) Asignar los datos actuales a su dueño ----------
do $$
declare
  v_email text := null;   -- <<< pon aquí el usuario dueño de los datos actuales, ej. 'antony@minegocio.app' (o deja null)
  v_owner uuid; v_slug text;
begin
  if v_email is not null then
    select id into v_owner from auth.users where lower(email) = lower(v_email);
    if v_owner is null then raise exception 'No existe el usuario %', v_email; end if;
  else
    select id, email into v_owner, v_email from auth.users order by created_at limit 1;
    if v_owner is null then raise exception 'Crea primero tu usuario en Authentication > Users'; end if;
  end if;

  v_slug := trim(both '-' from regexp_replace(lower(split_part(v_email, '@', 1)), '[^a-z0-9]+', '-', 'g'));
  if length(v_slug) < 2 then v_slug := 'tienda'; end if;

  update public.settings  set owner_id = v_owner, is_default = true, slug = coalesce(slug, v_slug) where owner_id is null;
  update public.products  set owner_id = v_owner where owner_id is null;
  update public.customers set owner_id = v_owner where owner_id is null;
  update public.orders    set owner_id = v_owner where owner_id is null;
end $$;

-- ---------- 3) Reglas de las nuevas columnas ----------
alter table public.settings  alter column owner_id set default auth.uid();
alter table public.products  alter column owner_id set default auth.uid();
alter table public.customers alter column owner_id set default auth.uid();
alter table public.orders    alter column owner_id set default auth.uid();
alter table public.settings  alter column owner_id set not null;
alter table public.products  alter column owner_id set not null;
alter table public.customers alter column owner_id set not null;
alter table public.orders    alter column owner_id set not null;

create unique index if not exists settings_owner_idx   on public.settings (owner_id);
create unique index if not exists settings_slug_idx    on public.settings (slug);
create unique index if not exists settings_default_idx on public.settings (is_default) where is_default;
alter table public.settings drop constraint if exists settings_slug_check;
alter table public.settings add constraint settings_slug_check check (slug ~ '^[a-z0-9][a-z0-9-]{1,29}$');

-- settings ya no es una sola fila (id = 1): ahora hay una por usuario
alter table public.settings drop constraint if exists settings_id_check;
alter table public.settings alter column id drop default;
alter table public.settings alter column id add generated by default as identity;
select setval(pg_get_serial_sequence('public.settings', 'id'), coalesce((select max(id) from public.settings), 1));

create index if not exists products_owner_idx  on public.products (owner_id);
create index if not exists customers_owner_idx on public.customers (owner_id);
create index if not exists orders_owner_idx    on public.orders (owner_id, created_at desc);

-- ---------- 4) Número de pedido correlativo por usuario (#1, #2, ...) ----------
alter table public.orders alter column number drop identity if exists;
create or replace function public.orders_set_number() returns trigger
language plpgsql as $$
begin
  if new.number is null then
    select coalesce(max(number), 0) + 1 into new.number from public.orders where owner_id = new.owner_id;
  end if;
  return new;
end $$;
drop trigger if exists orders_number on public.orders;
create trigger orders_number before insert on public.orders
  for each row execute function public.orders_set_number();
create unique index if not exists orders_owner_number_idx on public.orders (owner_id, number);

-- ---------- 5) Seguridad: cada usuario solo ve y modifica lo suyo ----------
drop policy if exists "dueno settings" on public.settings;
create policy "dueno settings" on public.settings
  for all to authenticated using (owner_id = auth.uid()) with check (owner_id = auth.uid());

drop policy if exists "dueno products" on public.products;
create policy "dueno products" on public.products
  for all to authenticated using (owner_id = auth.uid()) with check (owner_id = auth.uid());

drop policy if exists "dueno customers" on public.customers;
create policy "dueno customers" on public.customers
  for all to authenticated using (owner_id = auth.uid()) with check (owner_id = auth.uid());

drop policy if exists "dueno orders" on public.orders;
create policy "dueno orders" on public.orders
  for all to authenticated using (owner_id = auth.uid()) with check (owner_id = auth.uid());

drop policy if exists "dueno order_items" on public.order_items;
create policy "dueno order_items" on public.order_items
  for all to authenticated
  using (exists (select 1 from public.orders o where o.id = order_id and o.owner_id = auth.uid()))
  with check (exists (select 1 from public.orders o where o.id = order_id and o.owner_id = auth.uid()));

-- El catálogo público necesita saber de qué tienda es cada producto (nunca ve costos)
revoke select on public.products from anon;
grant select (id, owner_id, name, category, public_price, prices, image_url, images, description, active, created_at)
  on public.products to anon;
revoke select on public.settings from anon;
grant select (id, owner_id, slug, is_default, business_name, whatsapp, discount_levels) on public.settings to anon;

-- Fotos: cada usuario sube a su propia carpeta (USUARIO/PRODUCTO/foto.jpg)
drop policy if exists "subir fotos" on storage.objects;
create policy "subir fotos" on storage.objects
  for insert to authenticated
  with check (bucket_id = 'productos' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "editar fotos" on storage.objects;
create policy "editar fotos" on storage.objects
  for update to authenticated
  using (bucket_id = 'productos' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "borrar fotos" on storage.objects;
create policy "borrar fotos" on storage.objects
  for delete to authenticated
  using (bucket_id = 'productos' and (
    (storage.foldername(name))[1] = auth.uid()::text
    or exists (select 1 from public.products p where p.id::text = (storage.foldername(name))[1] and p.owner_id = auth.uid())  -- fotos antiguas
  ));

-- ---------- 6) Pedidos desde el catálogo: ahora indican la tienda (?t=SLUG) ----------
drop function if exists public.crear_pedido_catalogo(text, text, text, int, jsonb, text);

create or replace function public.crear_pedido_catalogo(
  p_nombre text, p_telefono text, p_nota text, p_descuento int, p_items jsonb,
  p_ref text default null, p_tienda text default null
) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  v_owner uuid; v_levels int[]; v_cost_pct int; v_d int; v_ref uuid;
  v_order_id uuid; v_number bigint;
  v_total numeric := 0; v_cost numeric := 0;
  it jsonb; v_p products%rowtype; v_qty int; v_price numeric; v_cost_u numeric;
begin
  if p_nombre is null or length(trim(p_nombre)) = 0 then raise exception 'Falta el nombre'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 50 then
    raise exception 'Pedido inválido';
  end if;

  if p_tienda is not null and length(trim(p_tienda)) > 0 then
    select owner_id, discount_levels, cost_discount_pct into v_owner, v_levels, v_cost_pct
      from settings where slug = lower(trim(p_tienda));
  else
    select owner_id, discount_levels, cost_discount_pct into v_owner, v_levels, v_cost_pct
      from settings where is_default;
  end if;
  if v_owner is null then raise exception 'Tienda no encontrada'; end if;
  v_d := case when p_descuento = any(v_levels) then p_descuento else 0 end;

  if p_ref is not null and length(trim(p_ref)) > 0 then
    select id into v_ref from customers where ref_code = lower(trim(p_ref)) and owner_id = v_owner;
  end if;

  insert into orders (owner_id, customer_name, customer_phone, discount_pct, note, source, status, referred_by)
  values (v_owner, left(trim(p_nombre), 80), left(coalesce(p_telefono, ''), 30), v_d, left(coalesce(p_nota, ''), 300), 'catalogo', 'pendiente', v_ref)
  returning id, number into v_order_id, v_number;

  for it in select * from jsonb_array_elements(p_items) loop
    v_qty := (it->>'qty')::int;
    if v_qty is null or v_qty < 1 or v_qty > 999 then raise exception 'Cantidad inválida'; end if;
    select * into v_p from products where id = (it->>'product_id')::uuid and active and owner_id = v_owner;
    if not found then raise exception 'Producto no disponible'; end if;

    v_price  := coalesce((v_p.prices ->> v_d::text)::numeric, round(v_p.public_price * (1 - v_d / 100.0), 2));
    v_cost_u := coalesce(v_p.cost, round(v_p.public_price * (1 - v_cost_pct / 100.0), 2));

    insert into order_items (order_id, product_id, product_name, qty, public_price, unit_price, unit_cost)
    values (v_order_id, v_p.id, v_p.name, v_qty, v_p.public_price, v_price, v_cost_u);

    v_total := v_total + v_qty * v_price;
    v_cost  := v_cost  + v_qty * v_cost_u;
  end loop;

  update orders set total = round(v_total, 2), cost = round(v_cost, 2) where id = v_order_id;
  return v_number;
end $$;

revoke all on function public.crear_pedido_catalogo(text, text, text, int, jsonb, text, text) from public;
grant execute on function public.crear_pedido_catalogo(text, text, text, int, jsonb, text, text) to anon, authenticated;

-- ---------- 7) El primer usuario que configure la app es la tienda principal (enlaces sin ?t=) ----------
create or replace function public.settings_set_default() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from settings where is_default) then new.is_default := true; end if;
  return new;
end $$;
drop trigger if exists settings_default on public.settings;
create trigger settings_default before insert on public.settings
  for each row execute function public.settings_set_default();
