-- =====================================================================
--  Esquema de base de datos para la app "Mi Negocio Herbalife"
--  Pegar completo en Supabase > SQL Editor > New query > Run
-- =====================================================================

create extension if not exists pgcrypto;

-- ---------- Ajustes del negocio (una sola fila) ----------
create table if not exists public.settings (
  id int primary key default 1 check (id = 1),
  business_name text not null default 'Mi Negocio Herbalife',
  whatsapp text not null default '',
  cost_discount_pct int not null default 50 check (cost_discount_pct between 0 and 100),
  discount_levels int[] not null default '{35,20,10,0}',
  updated_at timestamptz not null default now()
);
insert into public.settings (id) values (1) on conflict (id) do nothing;

-- ---------- Productos ----------
create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  category text not null default '',
  public_price numeric(10,2) not null check (public_price >= 0),
  cost numeric(10,2) check (cost is null or cost >= 0),   -- costo real (si es null se calcula con cost_discount_pct)
  prices jsonb not null default '{}'::jsonb,              -- precios fijados a mano por nivel: {"20": 190, "35": 155}
  description text not null default '',
  image_url text,                       -- foto principal (la primera de images)
  images text[] not null default '{}',  -- todas las fotos
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- ---------- Clientes ----------
create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  phone text not null default '',
  discount_pct int not null default 20 check (discount_pct between 0 and 100),
  notes text not null default '',
  ref_code text not null unique default substr(md5(gen_random_uuid()::text), 1, 6),  -- enlace personal: catalogo.html?ref=CODIGO
  created_at timestamptz not null default now()
);

-- ---------- Pedidos ----------
create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  number bigint generated by default as identity,            -- número correlativo visible (#12)
  customer_id uuid references public.customers(id) on delete set null,
  customer_name text not null default '',
  customer_phone text not null default '',                   -- teléfono cuando el pedido viene del catálogo
  source text not null default 'app' check (source in ('app', 'catalogo')),
  referred_by uuid references public.customers(id) on delete set null,   -- cliente que compartió su enlace
  discount_pct int not null default 0,
  status text not null default 'pendiente'
    check (status in ('pendiente','entregado','pagado','cancelado')),
  note text not null default '',
  total numeric(10,2) not null default 0,
  cost numeric(10,2) not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid references public.products(id) on delete set null,
  product_name text not null,
  qty int not null check (qty > 0),
  public_price numeric(10,2) not null,
  unit_price numeric(10,2) not null,
  unit_cost numeric(10,2) not null
);

create index if not exists orders_created_idx on public.orders (created_at desc);
create index if not exists order_items_order_idx on public.order_items (order_id);

-- ---------- Seguridad (RLS) ----------
alter table public.settings    enable row level security;
alter table public.products    enable row level security;
alter table public.customers   enable row level security;
alter table public.orders      enable row level security;
alter table public.order_items enable row level security;

-- Cualquiera (clientes con el enlace) puede ver el catálogo y los datos básicos del negocio,
-- pero nunca tus costos: se limitan las columnas visibles para anónimos
revoke select on public.products from anon;
grant select (id, name, category, public_price, prices, image_url, images, description, active, created_at)
  on public.products to anon;
revoke select on public.settings from anon;
grant select (id, business_name, whatsapp, discount_levels) on public.settings to anon;

drop policy if exists "catalogo publico" on public.products;
create policy "catalogo publico" on public.products
  for select to anon using (active = true);

drop policy if exists "ajustes publicos" on public.settings;
create policy "ajustes publicos" on public.settings
  for select to anon using (true);

-- Solo el dueño (usuario autenticado) puede ver y modificar todo
drop policy if exists "dueno settings" on public.settings;
create policy "dueno settings" on public.settings
  for all to authenticated using (true) with check (true);

drop policy if exists "dueno products" on public.products;
create policy "dueno products" on public.products
  for all to authenticated using (true) with check (true);

drop policy if exists "dueno customers" on public.customers;
create policy "dueno customers" on public.customers
  for all to authenticated using (true) with check (true);

drop policy if exists "dueno orders" on public.orders;
create policy "dueno orders" on public.orders
  for all to authenticated using (true) with check (true);

drop policy if exists "dueno order_items" on public.order_items;
create policy "dueno order_items" on public.order_items
  for all to authenticated using (true) with check (true);

-- ---------- Pedidos desde el catálogo público ----------
-- El catálogo no inserta directamente: llama a esta función, que valida y
-- recalcula precios y costos en el servidor y crea el pedido como "pendiente".
create or replace function public.crear_pedido_catalogo(
  p_nombre text, p_telefono text, p_nota text, p_descuento int, p_items jsonb, p_ref text default null
) returns bigint
language plpgsql security definer set search_path = public as $$
declare
  v_levels int[]; v_cost_pct int; v_d int; v_ref uuid;
  v_order_id uuid; v_number bigint;
  v_total numeric := 0; v_cost numeric := 0;
  it jsonb; v_p products%rowtype; v_qty int; v_price numeric; v_cost_u numeric;
begin
  if p_nombre is null or length(trim(p_nombre)) = 0 then raise exception 'Falta el nombre'; end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 50 then
    raise exception 'Pedido inválido';
  end if;

  select discount_levels, cost_discount_pct into v_levels, v_cost_pct from settings where id = 1;
  v_d := case when p_descuento = any(v_levels) then p_descuento else 0 end;

  if p_ref is not null and length(trim(p_ref)) > 0 then
    select id into v_ref from customers where ref_code = lower(trim(p_ref));
  end if;

  insert into orders (customer_name, customer_phone, discount_pct, note, source, status, referred_by)
  values (left(trim(p_nombre), 80), left(coalesce(p_telefono, ''), 30), v_d, left(coalesce(p_nota, ''), 300), 'catalogo', 'pendiente', v_ref)
  returning id, number into v_order_id, v_number;

  for it in select * from jsonb_array_elements(p_items) loop
    v_qty := (it->>'qty')::int;
    if v_qty is null or v_qty < 1 or v_qty > 999 then raise exception 'Cantidad inválida'; end if;
    select * into v_p from products where id = (it->>'product_id')::uuid and active;
    if not found then raise exception 'Producto no disponible'; end if;

    v_price  := coalesce((v_p.prices ->> v_d::text)::numeric, round(v_p.public_price * (1 - v_d / 100.0), 2));
    v_cost_u := coalesce(v_p.cost, round(v_p.public_price * (1 - v_cost_pct / 100.0), 2));

    insert into order_items (order_id, product_id, product_name, qty, public_price, unit_price, unit_cost)
    values (v_order_id, v_p.id, v_p.name, v_qty, v_p.public_price, v_price, v_cost_u);

    v_total := v_total + v_qty * v_price;
    v_cost  := v_cost  + v_qty * v_cost_u;
  end loop;

  update orders set total = round(v_total, 2), cost = round(v_cost, 2) where id = v_order_id;
  return v_number;
end $$;

revoke all on function public.crear_pedido_catalogo(text, text, text, int, jsonb, text) from public;
grant execute on function public.crear_pedido_catalogo(text, text, text, int, jsonb, text) to anon, authenticated;

-- ---------- Fotos de productos (Storage) ----------
insert into storage.buckets (id, name, public)
  values ('productos', 'productos', true)
  on conflict (id) do nothing;

drop policy if exists "fotos publicas" on storage.objects;
create policy "fotos publicas" on storage.objects
  for select to anon, authenticated using (bucket_id = 'productos');

drop policy if exists "subir fotos" on storage.objects;
create policy "subir fotos" on storage.objects
  for insert to authenticated with check (bucket_id = 'productos');

drop policy if exists "editar fotos" on storage.objects;
create policy "editar fotos" on storage.objects
  for update to authenticated using (bucket_id = 'productos');

drop policy if exists "borrar fotos" on storage.objects;
create policy "borrar fotos" on storage.objects
  for delete to authenticated using (bucket_id = 'productos');
